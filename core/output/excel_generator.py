def write_income_statement(
    workbook,
    financials,
):
    """
    Write historical income statement data
    into the Income Statement worksheet.
    """

    sheet = workbook["Income Statement"]

    sheet["A1"] = "Income Statement"

    headers = ["Metric"]

    for financial in financials:
        headers.append(financial.year)

    for column, header in enumerate(headers, start=1):
        sheet.cell(
            row=2,
            column=column,
            value=header,
        )

    metrics = [
        "Revenue",
        "COGS",
        "Gross Profit",
        "Operating Expenses",
        "EBITDA",
        "Depreciation",
        "EBIT",
        "Interest Expense",
        "EBT",
        "Taxes",
        "Net Income",
    ]

    for row, metric in enumerate(metrics, start=3):
        sheet.cell(
            row=row,
            column=1,
            value=metric,
        )

    for column, financial in enumerate(
        financials,
        start=2,
    ):
        revenue = financial.revenue
        cogs = financial.cogs
        operating_expenses = financial.operating_expenses
        depreciation = financial.depreciation
        interest_expense = financial.interest_expense
        taxes = financial.taxes

        gross_profit = revenue - cogs

        ebitda = (
            gross_profit
            - operating_expenses
        )

        ebit = ebitda - depreciation

        ebt = ebit - interest_expense

        net_income = ebt - taxes

        values = [
            revenue,
            cogs,
            gross_profit,
            operating_expenses,
            ebitda,
            depreciation,
            ebit,
            interest_expense,
            ebt,
            taxes,
            net_income,
        ]

        for row, value in enumerate(
            values,
            start=3,
        ):
            sheet.cell(
                row=row,
                column=column,
                value=round(value, 2),
            )

    return sheet
