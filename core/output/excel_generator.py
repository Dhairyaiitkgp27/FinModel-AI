def write_historical_financials(
    workbook,
    financials,
):
    """
    Write historical financial data into the
    Historical Financials worksheet.
    """

    sheet = workbook["Historical Financials"]

    headers = [
        "Year",
        "Revenue",
        "COGS",
        "Operating Expenses",
        "Depreciation",
        "Interest Expense",
        "Taxes",
        "Cash",
        "Total Debt",
        "Total Assets",
        "Shareholders Equity",
    ]

    for column, header in enumerate(headers, start=1):
        sheet.cell(
            row=1,
            column=column,
            value=header,
        )

    for row_number, financial in enumerate(
        financials,
        start=2,
    ):
        sheet.cell(row=row_number, column=1, value=financial.year)
        sheet.cell(row=row_number, column=2, value=financial.revenue)
        sheet.cell(row=row_number, column=3, value=financial.cogs)
        sheet.cell(
            row=row_number,
            column=4,
            value=financial.operating_expenses,
        )
        sheet.cell(
            row=row_number,
            column=5,
            value=financial.depreciation,
        )
        sheet.cell(
            row=row_number,
            column=6,
            value=financial.interest_expense,
        )
        sheet.cell(row=row_number, column=7, value=financial.taxes)
        sheet.cell(row=row_number, column=8, value=financial.cash)
        sheet.cell(row=row_number, column=9, value=financial.total_debt)
        sheet.cell(
            row=row_number,
            column=10,
            value=financial.total_assets,
        )
        sheet.cell(
            row=row_number,
            column=11,
            value=financial.shareholders_equity,
        )

    return sheet
