def create_financial_model_workbook(
    output_path,
    company_name,
):
    """
    Create the base financial model workbook.
    """

    workbook = Workbook()

    # Remove default sheet
    default_sheet = workbook.active
    workbook.remove(default_sheet)

    # Create model sections
    workbook.create_sheet("Cover")
    workbook.create_sheet("Assumptions")
    workbook.create_sheet("Historical Financials")
    workbook.create_sheet("Income Statement")
    workbook.create_sheet("Balance Sheet")
    workbook.create_sheet("Cash Flow")
    workbook.create_sheet("Free Cash Flow")
    workbook.create_sheet("DCF Valuation")
    workbook.create_sheet("Sensitivity")
    workbook.create_sheet("Scenarios")

    # Cover
    cover = workbook["Cover"]

    cover["A1"] = company_name
    cover["A2"] = "Automated Financial Model"
    cover["A3"] = "Generated by FinModel-AI"

    workbook.save(output_path)

    return output_path
