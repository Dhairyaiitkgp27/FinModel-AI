def create_financial_model_workbook(
    output_path,
    company_name,
):
    """
    Create and save the standard financial model workbook.
    """

    from openpyxl import Workbook

    workbook = Workbook()

    # Cover sheet
    cover = workbook.active
    cover.title = "Cover"

    cover["A1"] = company_name
    cover["A2"] = "Automated Financial Model"

    # Required model sheets
    sheet_names = [
        "Assumptions",
        "Historical Financials",
        "Income Statement",
        "Balance Sheet",
        "Cash Flow",
        "Free Cash Flow",
        "DCF Valuation",
        "Sensitivity",
        "Scenarios",
    ]

    for sheet_name in sheet_names:
        workbook.create_sheet(sheet_name)

    # Save workbook
    workbook.save(output_path)

    return output_path
