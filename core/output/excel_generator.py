def write_cash_flow(
    workbook,
    financials,
):
    """
    Write a simplified historical cash flow statement
    into the Cash Flow worksheet.
    """

    sheet = workbook["Cash Flow"]

    sheet["A1"] = "Cash Flow Statement"

    headers = ["Metric"]

    for financial in financials:
        headers.append(financial.year)

    for column, header in enumerate(headers, start=1):
        sheet.cell(
            row=2,
            column=column,
            value=header,
        )

    metrics = [
        "Net Income",
        "Depreciation",
        "Capital Expenditure",
        "Free Cash Flow",
    ]

    for row, metric in enumerate(metrics, start=3):
        sheet.cell(
            row=row,
            column=1,
            value=metric,
        )

    for column, financial in enumerate(
        financials,
        start=2,
    ):
        gross_profit = (
            financial.revenue
            - financial.cogs
        )

        ebitda = (
            gross_profit
            - financial.operating_expenses
        )

        ebit = ebitda - financial.depreciation

        ebt = (
            ebit
            - financial.interest_expense
        )

        net_income = ebt - financial.taxes

        # Historical model does not yet contain
        # a dedicated CapEx field, so use depreciation
        # as a temporary placeholder.
        capex = financial.depreciation

        free_cash_flow = (
            net_income
            + financial.depreciation
            - capex
        )

        values = [
            net_income,
            financial.depreciation,
            capex,
            free_cash_flow,
        ]

        for row, value in enumerate(
            values,
            start=3,
        ):
            sheet.cell(
                row=row,
                column=column,
                value=round(value, 2),
            )

    return sheet
def write_free_cash_flow(
    workbook,
    free_cash_flows,
    forecast_years,
):
    """
    Write forecast free cash flows into the
    Free Cash Flow worksheet.
    """

    sheet = workbook["Free Cash Flow"]

    sheet["A1"] = "Free Cash Flow"

    sheet["A2"] = "Metric"

    for column, year in enumerate(
        forecast_years,
        start=2,
    ):
        sheet.cell(
            row=2,
            column=column,
            value=year,
        )

    sheet["A3"] = "Free Cash Flow"

    for column, free_cash_flow in enumerate(
        free_cash_flows,
        start=2,
    ):
        sheet.cell(
            row=3,
            column=column,
            value=round(free_cash_flow, 2),
        )

    return sheet
def write_dcf_valuation(
    workbook,
    valuation,
):
    """
    Write DCF valuation results into the
    DCF Valuation worksheet.
    """

    sheet = workbook["DCF Valuation"]

    sheet["A1"] = "DCF Valuation"

    sheet["A3"] = "Enterprise Value"
    sheet["B3"] = valuation.enterprise_value

    sheet["A4"] = "Terminal Value"
    sheet["B4"] = valuation.terminal_value

    sheet["A5"] = "PV of Terminal Value"
    sheet["B5"] = valuation.terminal_present_value

    sheet["A6"] = "PV of Forecast FCF"

    pv_forecast_fcf = sum(
        valuation.present_values
    )

    sheet["B6"] = pv_forecast_fcf

    sheet["A8"] = "Total Debt"
    sheet["B8"] = valuation.total_debt

    sheet["A9"] = "Cash"
    sheet["B9"] = valuation.cash

    sheet["A10"] = "Equity Value"
    sheet["B10"] = valuation.equity_value

    sheet["A11"] = "Shares Outstanding"
    sheet["B11"] = valuation.shares_outstanding

    sheet["A12"] = "Implied Share Price"
    sheet["B12"] = valuation.implied_share_price

    return sheet
